#pragma once

#include <QString>

/**
 * @struct Habit
 * @brief Доменная сущность «привычка», зеркало таблицы habits.
 *
 * @details Соответствует текущей схеме PostgreSQL:
 * `habits(id SERIAL PRIMARY KEY, name TEXT NOT NULL, is_done BOOLEAN)`.
 * Используется как простой DTO между слоями db → logic → ui.
 * Когда в таблице появятся новые поля (дата создания, серия дней и т.п.),
 * достаточно расширить эту структуру — компилятор найдёт все места,
 * где нужно дописать обработку (защита от тихих ошибок).
 */
struct Habit
{
    int id = 0;             ///< Суррогатный ключ строки таблицы
    QString name;           ///< Отображаемое название привычки
    bool isDone = false;    ///< Выполнена ли привычка сегодня
};
